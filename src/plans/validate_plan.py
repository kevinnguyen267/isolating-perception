import threading
from pathlib import Path

from unified_planning.engines import SequentialPlanValidator
from unified_planning.io import PDDLReader
from unified_planning.plans import ActionInstance, SequentialPlan

_UP_LOCK = threading.Lock()


def _parse_fast_downward_plan(plan: str) -> list[tuple[str, list[str]]]:
    """Parse a Fast Downward SAS+ plan file into a list of (action_name, [args])."""
    actions = []
    for line in plan.splitlines():
        line = line.strip()
        if not line or line.startswith(";"):
            continue

        inner = line.strip("()")
        parts = inner.split()
        action_name = parts[0]
        args = parts[1:]
        actions.append((action_name, args))
    return actions


def _build_plan(problem, parsed_actions) -> SequentialPlan:
    """Convert parsed (action_name, args) tuples into a unified-planning SequentialPlan."""
    action_instances = []

    for action_name, arg_names in parsed_actions:
        # Look up the action in the unified planning problem object
        action = problem.action(action_name)

        # Resolve each argument string to a problem object
        actual_params = []
        for arg_name in arg_names:
            obj = problem.object(arg_name)
            actual_params.append(obj)

        action_instances.append(ActionInstance(action, tuple(actual_params)))

    return SequentialPlan(action_instances)


def validate_plan(
    domain_path: Path, problem_path: Path, plan: str
) -> tuple[bool, list[str]]:
    """Validate the plan generated by Fast Downward against the original problem using unified-planning's SequentialPlanValidator.

    Returns a tuple of (is_valid, log_messages) where is_valid is a boolean indicating if the plan is valid, and log_messages is a list of strings containing any messages from the validator.
    """
    if plan.startswith("FAST DOWNWARD ERROR:"):
        return False, [plan]

    domain_path_str = str(domain_path)
    problem_path_str = str(problem_path)

    # Parse the plan file to get a list of (action_name, [args]) tuples
    parsed_actions = _parse_fast_downward_plan(plan)

    with _UP_LOCK:
        # Parse the domain and problem files to get a unified planning problem object
        problem = PDDLReader().parse_problem(domain_path_str, problem_path_str)

        try:
            plan = _build_plan(problem, parsed_actions)
        except Exception as e:
            return False, [str(e)]

        with SequentialPlanValidator(problem_kind=problem.kind) as validator:
            result = validator.validate(problem, plan)

    return result.status.name == "VALID", [str(msg) for msg in result.log_messages]
